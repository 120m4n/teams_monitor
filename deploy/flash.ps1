# Writes firmware/esp8266/src/secrets.h from teams_monitor.xml and flashes the ESP8266 over USB.
# teams_monitor.exe holds the COM port, so it's closed while flashing and restarted afterwards.
# Without <wifi ssid> in the XML, secrets.h is removed and the firmware is serial-only.
#
#   powershell -ExecutionPolicy Bypass -File deploy\flash.ps1 -Config C:\Tools\teams_monitor.xml   # -Port COM16 to override
param(
    [string] $Config = (Join-Path $PSScriptRoot "..\teams_monitor.xml"),
    [string] $Port = ""
)
$ErrorActionPreference = "Stop"

$cfg = ([xml](Get-Content -Raw $Config)).teamsMonitor
if (-not $cfg) { throw "${Config}: missing <teamsMonitor> root" }

$fw      = Join-Path $PSScriptRoot "..\firmware\esp8266"
$secrets = Join-Path $fw "src\secrets.h"
$cstr    = { param($s) '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$wifi = $cfg.wifi
if ($wifi.ssid) {
    $lines = @(
        "// Generated by deploy/flash.ps1 from $([IO.Path]::GetFileName($Config)). Do not commit.",
        "#define WIFI_SSID $(& $cstr $wifi.ssid)",
        "#define WIFI_PASS $(& $cstr $wifi.password)"
    )
    if ($wifi.ip) {
        if (-not $wifi.gateway) { throw "${Config}: <wifi ip> needs gateway" }
        $subnet = if ($wifi.subnet) { $wifi.subnet } else { "255.255.255.0" }
        $lines += "#define WIFI_IP $(& $cstr $wifi.ip)", "#define WIFI_GATEWAY $(& $cstr $wifi.gateway)", "#define WIFI_SUBNET $(& $cstr $subnet)"
    }
    [IO.File]::WriteAllLines($secrets, $lines)   # UTF-8 without BOM
    Write-Host "secrets.h: WiFi '$($wifi.ssid)'$(if ($wifi.ip) { ", static IP $($wifi.ip)" } else { ', DHCP' })"
} else {
    Remove-Item $secrets -ErrorAction SilentlyContinue
    Write-Host "secrets.h: none (serial-only firmware)"
}

if (-not $Port) { $Port = $cfg.actuator.serial.port }
if (-not $Port) {
    $ports = [IO.Ports.SerialPort]::GetPortNames()
    if ($ports.Count -ne 1) { throw "no <serial port> in $Config and $($ports.Count) COM ports found; pass -Port COMx" }
    $Port = $ports[0]
}

$running = @(Get-CimInstance Win32_Process -Filter "Name='teams_monitor.exe'")
foreach ($p in $running) { Stop-Process -Id $p.ProcessId -Force }
if ($running) { Start-Sleep 1 }   # let Windows release the COM port
try {
    Push-Location $fw
    pio run -t upload --upload-port $Port
    if ($LASTEXITCODE -ne 0) { throw "pio upload failed ($LASTEXITCODE)" }
} finally {
    Pop-Location
    foreach ($p in $running) {
        $argv = $p.CommandLine -replace '^\s*("[^"]*"|\S+)\s*', ''   # drop the exe path
        if ($argv) { Start-Process $p.ExecutablePath -ArgumentList $argv } else { Start-Process $p.ExecutablePath }
    }
}
if ($wifi.ip) { Write-Host "HTTP: POST http://$($wifi.ip)/led" }
